-- 0001_core.sql - 核心业务表
-- 包含: chat/users/messages, groups/tracked, broadcast/push_tasks
-- 依赖: auth.users (将在 auth schema 中假设已存在或通过 extension 创建)

BEGIN;

-- =====================================================
-- SCHEMA: chat - 聊天相关核心表
-- =====================================================

-- chat.users 表 (用户基础信息)
CREATE TABLE IF NOT EXISTS chat.users (
    user_id bigint PRIMARY KEY,
    email text,
    username text,
    first_name text,
    last_name text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- chat.admin_inbox 表 (管理员收件箱)
CREATE TABLE IF NOT EXISTS chat.admin_inbox (
    user_id bigint PRIMARY KEY,
    username text,
    summary text,
    unread_count integer NOT NULL DEFAULT 0,
    last_active timestamptz NOT NULL DEFAULT now(),
    avatar_file_id text,
    tenant_id text NOT NULL DEFAULT 'default',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- chat.messages 表 (私聊消息)
CREATE TABLE IF NOT EXISTS chat.messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trace_id text UNIQUE,
    from_userid bigint NOT NULL,
    to_userid bigint NOT NULL,
    content text,
    msg_type text NOT NULL DEFAULT 'text',
    file_id text,
    media_url text,
    timestamp timestamptz NOT NULL DEFAULT now(),
    is_read boolean NOT NULL DEFAULT false,
    quoted_text text,
    quoted_msg_id bigint,
    quoted_file_id text,
    quoted_type text NOT NULL DEFAULT 'text',
    tg_msg_id bigint,
    status text NOT NULL DEFAULT 'sent',
    auto_translation text,
    original_text text,
    translated_text text,
    admin_userid text,
    is_deleted boolean NOT NULL DEFAULT false,
    tenant_id text NOT NULL DEFAULT 'default'
);

-- chat.emoji_messages 表 (消息表情反应)
CREATE TABLE IF NOT EXISTS chat.emoji_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    msg_id bigint NOT NULL REFERENCES chat.messages(id) ON DELETE CASCADE,
    emoji text,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- =====================================================
-- SCHEMA: groups - 群组相关表
-- =====================================================

-- groups.tracked_groups 表 (群组监听主表)
CREATE TABLE IF NOT EXISTS groups.tracked_groups (
    group_id bigint PRIMARY KEY,
    group_title text,
    tenant_id text NOT NULL DEFAULT 'default',
    is_monitored boolean NOT NULL DEFAULT false,
    custom_keywords text,
    first_seen timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    delete_on_revoke boolean NOT NULL DEFAULT false,
    revoke_sync_chat_id bigint,
    verify_enabled boolean NOT NULL DEFAULT false,
    verify_type text NOT NULL DEFAULT 'captcha',
    verify_timeout integer NOT NULL DEFAULT 120,
    verify_channel_id text,
    verify_questions text,
    verify_msg_template text
);

-- groups.group_members 表 (群组成员)
CREATE TABLE IF NOT EXISTS groups.group_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    username text,
    first_name text,
    last_name text,
    group_id bigint NOT NULL,
    group_title text,
    tenant_id text NOT NULL DEFAULT 'default',
    status text NOT NULL DEFAULT 'active',
    joined_at timestamptz NOT NULL DEFAULT now(),
    is_verified boolean NOT NULL DEFAULT false,
    verified_at timestamptz,
    avatar_file_id text,
    pending_verify_msg_id bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(group_id, user_id)
);

-- groups.group_messages 表 (群组消息记录)
CREATE TABLE IF NOT EXISTS groups.group_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id bigint NOT NULL,
    user_id bigint NOT NULL,
    username text,
    tg_msg_id bigint,
    sender_type text NOT NULL DEFAULT 'user',
    content text,
    msg_type text NOT NULL DEFAULT 'text',
    file_id text,
    quoted_tg_msg_id bigint,
    quoted_text text,
    avatar_file_id text,
    timestamp timestamptz NOT NULL DEFAULT now(),
    message_ts integer,
    revoke_checked boolean NOT NULL DEFAULT false,
    is_advertising boolean NOT NULL DEFAULT false,
    ad_score integer NOT NULL DEFAULT 0,
    ad_confidence text NOT NULL DEFAULT 'low',
    ad_findings text,
    tenant_id text NOT NULL DEFAULT 'default'
);

-- groups.verify_sessions 表 (入群验证会话)
CREATE TABLE IF NOT EXISTS groups.verify_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id bigint NOT NULL,
    user_id bigint NOT NULL,
    username text,
    first_name text,
    verify_type text NOT NULL,
    answer text,
    bot_msg_id bigint,
    status text NOT NULL DEFAULT 'pending',
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz
);

-- groups.verified_users 表 (已验证用户 - 可通过 group_members.is_verified 查询)
-- 注意: verified 状态已保存在 group_members.is_verified，此表可选用于快速查询

-- groups.channel_reminders 表 (频道关注提醒)
CREATE TABLE IF NOT EXISTS groups.channel_reminders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id bigint NOT NULL,
    user_id bigint NOT NULL,
    message_id bigint NOT NULL,
    sent_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    is_deleted boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- groups.group_address_hits 表 (群内地址自动识别去重)
CREATE TABLE IF NOT EXISTS groups.group_address_hits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id bigint NOT NULL,
    user_id bigint,
    address text NOT NULL,
    network text NOT NULL,
    source_tg_msg_id bigint,
    query_result text,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(group_id, address)
);

-- =====================================================
-- SCHEMA: broadcast - 广播相关表
-- =====================================================

-- broadcast.broadcast_targets 表 (广播目标)
CREATE TABLE IF NOT EXISTS broadcast.broadcast_targets (
    chat_id bigint PRIMARY KEY,
    chat_title text,
    chat_type text NOT NULL,
    chat_username text,
    can_broadcast boolean NOT NULL DEFAULT true,
    tenant_id text NOT NULL DEFAULT 'default',
    updated_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- broadcast.push_tasks 表 (定时推送任务)
CREATE TABLE IF NOT EXISTS broadcast.push_tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_name text NOT NULL,
    content text,
    image_file_id text,
    do_translate boolean NOT NULL DEFAULT false,
    target_chat_ids text NOT NULL, -- JSON array stored as text
    start_at text NOT NULL,
    interval_hours integer NOT NULL,
    status text NOT NULL DEFAULT 'running',
    next_run_at text,
    last_run_at text,
    last_result text,
    last_summary text,
    retry_count integer NOT NULL DEFAULT 0,
    tenant_id text NOT NULL DEFAULT 'default',
    created_by bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- =====================================================
-- INDEXES: 核心表索引
-- =====================================================

-- chat.messages indexes
CREATE INDEX IF NOT EXISTS idx_messages_tenant ON chat.messages(tenant_id);
CREATE INDEX IF NOT EXISTS idx_messages_from_user ON chat.messages(from_userid);
CREATE INDEX IF NOT EXISTS idx_messages_to_user ON chat.messages(to_userid);
CREATE INDEX IF NOT EXISTS idx_messages_timestamp ON chat.messages(timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_messages_trace ON chat.messages(trace_id);

-- chat.emoji_messages indexes
CREATE INDEX IF NOT EXISTS idx_emoji_messages_msg ON chat.emoji_messages(msg_id);

-- groups.tracked_groups indexes
CREATE INDEX IF NOT EXISTS idx_tracked_groups_tenant ON groups.tracked_groups(tenant_id);
CREATE INDEX IF NOT EXISTS idx_tracked_groups_monitored ON groups.tracked_groups(is_monitored);

-- groups.group_members indexes
CREATE INDEX IF NOT EXISTS idx_group_members_tenant ON groups.group_members(tenant_id);
CREATE INDEX IF NOT EXISTS idx_group_members_group ON groups.group_members(group_id);
CREATE INDEX IF NOT EXISTS idx_group_members_user ON groups.group_members(user_id);

-- groups.group_messages indexes
CREATE INDEX IF NOT EXISTS idx_group_messages_tenant ON groups.group_messages(tenant_id);
CREATE INDEX IF NOT EXISTS idx_group_messages_group ON groups.group_messages(group_id, timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_group_messages_ts ON groups.group_messages(group_id, message_ts DESC);
CREATE INDEX IF NOT EXISTS idx_group_messages_ad ON groups.group_messages(group_id, is_advertising, ad_score DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_group_messages_tg ON groups.group_messages(group_id, tg_msg_id) WHERE tg_msg_id IS NOT NULL;

-- groups.verify_sessions indexes
CREATE INDEX IF NOT EXISTS idx_verify_sessions_group_user ON groups.verify_sessions(group_id, user_id);
CREATE INDEX IF NOT EXISTS idx_verify_sessions_status ON groups.verify_sessions(status, expires_at);

-- groups.channel_reminders indexes
CREATE INDEX IF NOT EXISTS idx_channel_reminders_user_group ON groups.channel_reminders(user_id, group_id);
CREATE INDEX IF NOT EXISTS idx_channel_reminders_expires ON groups.channel_reminders(expires_at) WHERE is_deleted = false;

-- groups.group_address_hits indexes
CREATE INDEX IF NOT EXISTS idx_group_address_hits_group ON groups.group_address_hits(group_id);

-- broadcast.broadcast_targets indexes
CREATE INDEX IF NOT EXISTS idx_broadcast_targets_tenant ON broadcast.broadcast_targets(tenant_id);

-- broadcast.push_tasks indexes
CREATE INDEX IF NOT EXISTS idx_push_tasks_tenant ON broadcast.push_tasks(tenant_id);
CREATE INDEX IF NOT EXISTS idx_push_tasks_status ON broadcast.push_tasks(status, next_run_at);

