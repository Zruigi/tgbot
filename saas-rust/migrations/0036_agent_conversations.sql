-- 0036_agent_conversations.sql - Agent 对话历史持久化
-- 解决：Agent 聊天记录不落库（只存进程内内存 TTL 6h），前端进入 Agent 会话永远空白
--
-- 注意：应用本迁移时请以应用连接角色（ubuntu）执行或随后 ALTER OWNER，
-- 否则 RLS（tenant_id = current_setting('app.tenant_id')) 会挡住应用查询。

BEGIN;

CREATE SCHEMA IF NOT EXISTS agent;

CREATE TABLE IF NOT EXISTS agent.conversations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id text NOT NULL DEFAULT 'default',
    merchant_id uuid,
    actor_key text NOT NULL,
    user_id bigint NOT NULL DEFAULT 0,
    role text NOT NULL CHECK (role IN ('user', 'assistant')),
    content text,
    msg_type text NOT NULL DEFAULT 'text',
    tool_calls_made jsonb NOT NULL DEFAULT '[]'::jsonb,
    requires_confirmation boolean NOT NULL DEFAULT false,
    media_url text,
    status text NOT NULL DEFAULT 'ok',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_agent_conv_tenant_actor
    ON agent.conversations (tenant_id, actor_key, id DESC);
CREATE INDEX IF NOT EXISTS idx_agent_conv_user
    ON agent.conversations (user_id);

ALTER TABLE agent.conversations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS agent_conv_tenant ON agent.conversations;
CREATE POLICY agent_conv_tenant ON agent.conversations
    FOR ALL USING (tenant_id = current_setting('app.tenant_id', true));

COMMIT;
