-- 0004_monitor_finance.sql - Monitor/Finance API Tables
-- 包含: address_monitors, monitor_transactions, finance_ledgers, chart_of_accounts

BEGIN;

-- =====================================================
-- SCHEMA: monitor - 钱包监控相关表
-- =====================================================

-- address_monitors 表 (钱包监听)
CREATE TABLE IF NOT EXISTS address_monitors (
    monitor_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    tenant_id text NOT NULL DEFAULT 'default',
    address text NOT NULL,
    network text NOT NULL DEFAULT 'TRC20',
    remark text DEFAULT '',
    risk_level text NOT NULL DEFAULT 'normal',
    risk_note text,
    is_active boolean NOT NULL DEFAULT true,
    last_tx_timestamp bigint,
    inflow_20 numeric(30, 8) NOT NULL DEFAULT 0,
    outflow_20 numeric(30, 8) NOT NULL DEFAULT 0,
    profit_20 numeric(30, 8) NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(address, network, tenant_id)
);

-- monitor_transactions 表 (交易记录)
CREATE TABLE IF NOT EXISTS monitor_transactions (
    tx_id text PRIMARY KEY,
    monitor_id bigint NOT NULL REFERENCES address_monitors(monitor_id) ON DELETE CASCADE,
    user_id bigint NOT NULL,
    tenant_id text NOT NULL DEFAULT 'default',
    address text NOT NULL,
    network text NOT NULL DEFAULT 'TRC20',
    direction text NOT NULL CHECK (direction IN ('in', 'out')),
    amount numeric(30, 8) NOT NULL DEFAULT 0,
    token_symbol text NOT NULL DEFAULT 'USDT',
    tx_timestamp bigint NOT NULL,
    counterparty text,
    risk_level text NOT NULL DEFAULT 'normal',
    risk_note text,
    -- 业务标注字段
    income_reason text,
    expense_reason text,
    payer text,
    payee text,
    is_energy_fee boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- monitor_counterparty_labels 表 (交易对手标签)
CREATE TABLE IF NOT EXISTS monitor_counterparty_labels (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id text NOT NULL DEFAULT 'default',
    counterparty text NOT NULL,
    network text NOT NULL DEFAULT 'TRC20',
    label text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(tenant_id, counterparty, network)
);

-- =====================================================
-- SCHEMA: finance - 财务相关表
-- =====================================================

-- finance_ledgers 表 (财务流水)
CREATE TABLE IF NOT EXISTS finance_ledgers (
    ledger_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    monitor_id bigint REFERENCES address_monitors(monitor_id) ON DELETE SET NULL,
    user_id bigint NOT NULL,
    tenant_id text NOT NULL DEFAULT 'default',
    tx_id text,
    direction text NOT NULL CHECK (direction IN ('in', 'out')),
    amount numeric(30, 8) NOT NULL DEFAULT 0,
    token_symbol text NOT NULL DEFAULT 'USDT',
    network text NOT NULL DEFAULT 'TRC20',
    base_fiat_value numeric(30, 2) NOT NULL DEFAULT 0,
    fiat_currency text NOT NULL DEFAULT 'USD',
    exchange_rate numeric(30, 8),
    counterparty text,
    account_id bigint,
    reconciled_status text NOT NULL DEFAULT 'UNRECONCILED',
    tx_hash text,
    tx_timestamp bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- chart_of_accounts 表 (会计科目)
CREATE TABLE IF NOT EXISTS chart_of_accounts (
    account_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL,
    type text NOT NULL CHECK (type IN ('asset', 'liability', 'income', 'expense', 'equity')),
    parent_id bigint REFERENCES chart_of_accounts(account_id) ON DELETE SET NULL,
    description text,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- finance_exchange_rates 表 (汇率存储)
CREATE TABLE IF NOT EXISTS finance_exchange_rates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_symbol text NOT NULL,
    fiat_currency text NOT NULL,
    rate numeric(30, 8) NOT NULL,
    rate_timestamp bigint NOT NULL,
    source text DEFAULT 'binance',
    created_at timestamptz NOT NULL DEFAULT now()
);

-- finance_audit_logs 表 (财务审计日志)
CREATE TABLE IF NOT EXISTS finance_audit_logs (
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id text NOT NULL DEFAULT 'default',
    timestamp timestamptz NOT NULL DEFAULT now(),
    admin_userid bigint NOT NULL,
    action text NOT NULL,
    target_table text NOT NULL,
    target_id text,
    reason text,
    ip_address text,
    before_state jsonb,
    after_state jsonb
);

-- =====================================================
-- INDEXES: 监控相关索引
-- =====================================================

CREATE INDEX IF NOT EXISTS idx_address_monitors_tenant ON address_monitors(tenant_id, is_active);
CREATE INDEX IF NOT EXISTS idx_address_monitors_user ON address_monitors(user_id);
CREATE INDEX IF NOT EXISTS idx_address_monitors_address ON address_monitors(address, network);

CREATE INDEX IF NOT EXISTS idx_monitor_transactions_tenant ON monitor_transactions(tenant_id, tx_timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_monitor_transactions_monitor ON monitor_transactions(monitor_id, tx_timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_monitor_transactions_timestamp ON monitor_transactions(tx_timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_monitor_transactions_direction ON monitor_transactions(direction);

CREATE INDEX IF NOT EXISTS idx_monitor_counterparty_labels_tenant ON monitor_counterparty_labels(tenant_id, counterparty);

-- =====================================================
-- INDEXES: 财务相关索引
-- =====================================================

CREATE INDEX IF NOT EXISTS idx_finance_ledgers_tenant ON finance_ledgers(tenant_id, reconciled_status, tx_timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_finance_ledgers_monitor ON finance_ledgers(monitor_id);
CREATE INDEX IF NOT EXISTS idx_finance_ledgers_user ON finance_ledgers(user_id, tx_timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_finance_ledgers_reconciled ON finance_ledgers(reconciled_status);

CREATE INDEX IF NOT EXISTS idx_chart_of_accounts_code ON chart_of_accounts(code);
CREATE INDEX IF NOT EXISTS idx_chart_of_accounts_parent ON chart_of_accounts(parent_id);
CREATE INDEX IF NOT EXISTS idx_chart_of_accounts_type ON chart_of_accounts(type);

CREATE INDEX IF NOT EXISTS idx_finance_exchange_rates_key ON finance_exchange_rates(token_symbol, fiat_currency, rate_timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_finance_audit_logs_tenant ON finance_audit_logs(tenant_id, timestamp DESC);

