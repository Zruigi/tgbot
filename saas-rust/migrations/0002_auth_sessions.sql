-- 0002_auth_sessions.sql - 认证与会话相关表
-- 包含: admin_sessions, web_login_otps, miniapp_grants, csrf_tokens
-- 依赖: auth.users (假设已在 0001_saas_core.sql 或 auth schema 中创建)

BEGIN;

-- =====================================================
-- SCHEMA: auth - 认证与会话
-- =====================================================

-- auth.users 表 (认证用户主表 - 如果尚未创建)
-- 注意: 如果 0001_saas_core.sql 已创建，则跳过此表
CREATE TABLE IF NOT EXISTS auth.users (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tg_user_id bigint UNIQUE,
    username text,
    first_name text,
    last_name text,
    email text,
    password_hash text,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- auth.saas_user_roles 表 (平台角色)
CREATE TABLE IF NOT EXISTS auth.saas_user_roles (
    user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    role text NOT NULL CHECK (role IN ('platform_admin', 'merchant_owner', 'merchant_admin', 'merchant_viewer')),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, role)
);

-- auth.admin_sessions 表 (管理员 Web Session)
CREATE TABLE IF NOT EXISTS auth.admin_sessions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    session_token text NOT NULL UNIQUE,
    refresh_token text,
    ip_address text,
    user_agent text,
    expires_at timestamptz NOT NULL,
    last_active_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- auth.web_login_otps 表 (Web OTP 登录)
CREATE TABLE IF NOT EXISTS auth.web_login_otps (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    otp_hash text NOT NULL UNIQUE,
    role text NOT NULL DEFAULT 'platform_admin',
    tenant_id text NOT NULL DEFAULT '',
    merchant_id bigint,
    issued_for text,
    expires_at timestamptz NOT NULL,
    used_at timestamptz,
    session_token text,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- auth.miniapp_grants 表 (Mini App 授权)
CREATE TABLE IF NOT EXISTS auth.miniapp_grants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grant_hash text NOT NULL UNIQUE,
    user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    issued_for text NOT NULL,
    role_hint text NOT NULL DEFAULT 'platform_admin',
    tenant_id text NOT NULL DEFAULT '',
    merchant_id bigint,
    entry_intent text NOT NULL DEFAULT 'menu',
    ua_fingerprint text,
    proof_salt text NOT NULL,
    expires_at timestamptz NOT NULL,
    last_rotated_at timestamptz,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- auth.csrf_tokens 表 (CSRF 防护)
CREATE TABLE IF NOT EXISTS auth.csrf_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token text NOT NULL UNIQUE,
    session_id text,
    ip_address text,
    user_agent text,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- =====================================================
-- INDEXES: 认证表索引
-- =====================================================

-- auth.users indexes
CREATE INDEX IF NOT EXISTS idx_auth_users_tg ON auth.users(tg_user_id);
CREATE INDEX IF NOT EXISTS idx_auth_users_email ON auth.users(email) WHERE email IS NOT NULL;

-- auth.saas_user_roles indexes
CREATE INDEX IF NOT EXISTS idx_saas_user_roles_user ON auth.saas_user_roles(user_id);
CREATE INDEX IF NOT EXISTS idx_saas_user_roles_role ON auth.saas_user_roles(role);

-- auth.admin_sessions indexes
CREATE INDEX IF NOT EXISTS idx_admin_sessions_user ON auth.admin_sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_admin_sessions_token ON auth.admin_sessions(session_token);
CREATE INDEX IF NOT EXISTS idx_admin_sessions_expires ON auth.admin_sessions(expires_at);

-- auth.web_login_otps indexes
CREATE INDEX IF NOT EXISTS idx_web_login_otps_hash ON auth.web_login_otps(otp_hash);
CREATE INDEX IF NOT EXISTS idx_web_login_otps_expires ON auth.web_login_otps(expires_at, used_at);
CREATE INDEX IF NOT EXISTS idx_web_login_otps_tenant ON auth.web_login_otps(tenant_id);
CREATE INDEX IF NOT EXISTS idx_web_login_otps_merchant ON auth.web_login_otps(merchant_id);

-- auth.miniapp_grants indexes
CREATE INDEX IF NOT EXISTS idx_miniapp_grants_hash ON auth.miniapp_grants(grant_hash);
CREATE INDEX IF NOT EXISTS idx_miniapp_grants_lookup ON auth.miniapp_grants(grant_hash, revoked_at, expires_at);
CREATE INDEX IF NOT EXISTS idx_miniapp_grants_user ON auth.miniapp_grants(user_id);
CREATE INDEX IF NOT EXISTS idx_miniapp_grants_tenant ON auth.miniapp_grants(tenant_id);

-- auth.csrf_tokens indexes
CREATE INDEX IF NOT EXISTS idx_csrf_tokens_token ON auth.csrf_tokens(token);
CREATE INDEX IF NOT EXISTS idx_csrf_tokens_expires ON auth.csrf_tokens(expires_at);

-- =====================================================
-- FUNCTIONS: 认证相关辅助函数
-- =====================================================

-- 清理过期 sessions 的函数
CREATE OR REPLACE FUNCTION auth.cleanup_expired_sessions()
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    -- 清理过期的 admin_sessions
    DELETE FROM auth.admin_sessions WHERE expires_at < now();

    -- 清理过期的 web_login_otps
    DELETE FROM auth.web_login_otps WHERE expires_at < now() OR used_at IS NOT NULL;

    -- 清理过期的 csrf_tokens
    DELETE FROM auth.csrf_tokens WHERE expires_at < now();

    -- 清理过期的 miniapp_grants
    DELETE FROM auth.miniapp_grants WHERE revoked_at IS NOT NULL OR expires_at < now();
END;
$$;

-- =====================================================
-- ROW LEVEL SECURITY (RLS)
-- =====================================================

ALTER TABLE auth.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth.saas_user_roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth.admin_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth.web_login_otps ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth.miniapp_grants ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth.csrf_tokens ENABLE ROW LEVEL SECURITY;

-- RLS Policies

-- auth.users: 所有人都可以注册，登录后可查看自己的信息
DROP POLICY IF EXISTS users_insert ON auth.users;
CREATE POLICY users_insert ON auth.users FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS users_select_own ON auth.users;
CREATE POLICY users_select_own ON auth.users FOR SELECT USING (id = auth.uid());

DROP POLICY IF EXISTS users_update_own ON auth.users;
CREATE POLICY users_update_own ON auth.users FOR UPDATE USING (id = auth.uid());

-- auth.saas_user_roles: 平台管理员可管理角色
DROP POLICY IF EXISTS saas_user_roles_select ON auth.saas_user_roles;
CREATE POLICY saas_user_roles_select ON auth.saas_user_roles FOR SELECT USING (
    EXISTS (SELECT 1 FROM auth.saas_user_roles r WHERE r.user_id = auth.uid() AND r.role = 'platform_admin')
    OR user_id = auth.uid()
);

-- auth.admin_sessions: 用户只能看到自己的 session
DROP POLICY IF EXISTS admin_sessions_select_own ON auth.admin_sessions;
CREATE POLICY admin_sessions_select_own ON auth.admin_sessions FOR SELECT USING (user_id = auth.uid());

DROP POLICY IF EXISTS admin_sessions_insert ON auth.admin_sessions;
CREATE POLICY admin_sessions_insert ON auth.admin_sessions FOR INSERT WITH CHECK (user_id = auth.uid());

DROP POLICY IF EXISTS admin_sessions_delete_own ON auth.admin_sessions;
CREATE POLICY admin_sessions_delete_own ON auth.admin_sessions FOR DELETE USING (user_id = auth.uid());

-- auth.web_login_otps: 用于验证 OTP，不启用 RLS 读取，通过 hash 查询
-- auth.miniapp_grants: 用于验证 grant，不启用 RLS 读取，通过 hash 查询
-- auth.csrf_tokens: 用于验证 CSRF，不启用 RLS 读取

COMMIT;