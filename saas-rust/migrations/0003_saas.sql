-- 0003_saas.sql - SaaS 多商户补充表
-- 包含: potential_users, admin_users, pending_admin_messages, admin_settings 等
-- 依赖: public.merchants, public.subscription_plans (已在 0001_saas_core.sql 创建)

BEGIN;

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE SCHEMA IF NOT EXISTS tenant_saas;
CREATE SCHEMA IF NOT EXISTS platform;
CREATE SCHEMA IF NOT EXISTS oneapi;
CREATE SCHEMA IF NOT EXISTS chain_sync;

-- =====================================================
-- SCHEMA: tenant_saas - 商户与租户管理补充表
-- =====================================================

-- tenant_saas.potential_users 表 (潜在用户/客户档案)
CREATE TABLE IF NOT EXISTS tenant_saas.potential_users (
    user_id bigint NOT NULL,
    username text,
    first_name text,
    last_name text,
    message_text text,
    keywords text,
    profile_tags text,
    group_id bigint,
    group_title text,
    tenant_id text NOT NULL DEFAULT 'default',
    captured_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, user_id)
);

-- tenant_saas.tenant_memberships 表 (��户成员关系 - 如果 0001 未创建)
-- 注意: 如果 0001_saas_core.sql 已创建，则此表应存在于 tenant_saas schema
-- 这里提供备选创建，如果已存在则不会重复创建

-- tenant_saas.tenant_configs 表 (租户配置密钥存储)
CREATE TABLE IF NOT EXISTS tenant_saas.tenant_configs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id text NOT NULL DEFAULT 'default',
    config_key text NOT NULL,
    config_value text, -- 加密存储
    remark text,
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(tenant_id, config_key)
);

-- tenant_saas.ai_custom_skills 表（按租户隔离的 AI 技能）
CREATE TABLE IF NOT EXISTS tenant_saas.ai_custom_skills (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id text NOT NULL DEFAULT 'default',
    name text NOT NULL,
    description text NOT NULL DEFAULT '',
    prompt_template text NOT NULL DEFAULT '',
    source text NOT NULL DEFAULT 'custom',
    is_enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(tenant_id, name)
);

-- public.merchant_onboarding 表 (商户入驻流程状态)
CREATE TABLE IF NOT EXISTS public.merchant_onboarding (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id uuid NOT NULL REFERENCES public.merchants(id) ON DELETE CASCADE,
    tenant_id text NOT NULL,
    step text NOT NULL DEFAULT 'started',
    status text NOT NULL DEFAULT 'in_progress',
    completed_at timestamptz,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- =====================================================
-- SCHEMA: platform - 平台管理补充表
-- =====================================================

-- platform.admin_users 表 (平台管理员/客服)
CREATE TABLE IF NOT EXISTS platform.admin_users (
    admin_id bigint PRIMARY KEY,
    username text,
    worker_no text,
    role text NOT NULL DEFAULT 'staff',
    is_online boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- platform.admin_settings 表 (平台设置)
CREATE TABLE IF NOT EXISTS platform.admin_settings (
    key text PRIMARY KEY,
    value text NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- platform.admin_message_mapping 表 (管理员消息映射)
CREATE TABLE IF NOT EXISTS platform.admin_message_mapping (
    admin_msg_id bigint PRIMARY KEY,
    user_id bigint NOT NULL,
    original_tg_msg_id bigint,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- platform.pending_admin_messages 表 (待确认的管理员消息)
CREATE TABLE IF NOT EXISTS platform.pending_admin_messages (
    msg_uuid text PRIMARY KEY,
    admin_id bigint NOT NULL,
    content text,
    msg_type text NOT NULL DEFAULT 'text',
    file_id text,
    status text NOT NULL DEFAULT 'pending',
    timestamp timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- =====================================================
-- SCHEMA: oneapi - API 密钥管理
-- =====================================================

-- oneapi.oneapi_keys 表 (OneAPI Key 映射)
CREATE TABLE IF NOT EXISTS oneapi.oneapi_keys (
    sk_token text PRIMARY KEY,
    provider text NOT NULL DEFAULT 'vertex_gemini',
    model text,
    sandbox_id text NOT NULL DEFAULT 'default',
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- =====================================================
-- SCHEMA: chain_sync - 区块链同步状态
-- =====================================================

-- chain_sync.chain_sync_state 表 (区块扫描状态)
CREATE TABLE IF NOT EXISTS chain_sync.chain_sync_state (
    network text PRIMARY KEY,
    last_scanned_block integer NOT NULL DEFAULT 0,
    last_scanned_ts integer NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- =====================================================
-- INDEXES: ���充表索引
-- =====================================================

-- tenant_saas.potential_users indexes
CREATE INDEX IF NOT EXISTS idx_potential_users_tenant ON tenant_saas.potential_users(tenant_id);
CREATE INDEX IF NOT EXISTS idx_potential_users_group ON tenant_saas.potential_users(group_id);
CREATE INDEX IF NOT EXISTS idx_potential_users_keywords ON tenant_saas.potential_users USING gin(keywords gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_potential_users_tags ON tenant_saas.potential_users USING gin(profile_tags gin_trgm_ops);

-- tenant_saas.tenant_configs indexes
CREATE INDEX IF NOT EXISTS idx_tenant_configs_tenant ON tenant_saas.tenant_configs(tenant_id);
CREATE INDEX IF NOT EXISTS idx_ai_custom_skills_tenant ON tenant_saas.ai_custom_skills(tenant_id, updated_at DESC);

-- public.merchant_onboarding indexes
CREATE INDEX IF NOT EXISTS idx_merchant_onboarding_merchant ON public.merchant_onboarding(merchant_id);
CREATE INDEX IF NOT EXISTS idx_merchant_onboarding_tenant ON public.merchant_onboarding(tenant_id);

-- platform.admin_users indexes
CREATE INDEX IF NOT EXISTS idx_admin_users_worker ON platform.admin_users(worker_no);
CREATE INDEX IF NOT EXISTS idx_admin_users_role ON platform.admin_users(role);

-- platform.pending_admin_messages indexes
CREATE INDEX IF NOT EXISTS idx_pending_admin_messages_admin ON platform.pending_admin_messages(admin_id, status);
CREATE INDEX IF NOT EXISTS idx_pending_admin_messages_status ON platform.pending_admin_messages(status, timestamp);

-- oneapi.oneapi_keys indexes
CREATE INDEX IF NOT EXISTS idx_oneapi_keys_sandbox ON oneapi.oneapi_keys(sandbox_id);
CREATE INDEX IF NOT EXISTS idx_oneapi_keys_active ON oneapi.oneapi_keys(is_active);

