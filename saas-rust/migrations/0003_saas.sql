-- =====================================================
-- ROW LEVEL SECURITY (RLS)
-- =====================================================

ALTER TABLE tenant_saas.potential_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE tenant_saas.tenant_configs ENABLE ROW LEVEL SECURITY;
ALTER TABLE tenant_saas.ai_custom_skills ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.merchant_onboarding ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.admin_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.admin_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.pending_admin_messages ENABLE ROW LEVEL SECURITY;

-- RLS Policies for tenant isolation

DROP POLICY IF EXISTS potential_users_tenant ON tenant_saas.potential_users;
CREATE POLICY potential_users_tenant ON tenant_saas.potential_users
    FOR ALL USING (tenant_id = current_setting('app.tenant_id', true));

DROP POLICY IF EXISTS tenant_configs_tenant ON tenant_saas.tenant_configs;
CREATE POLICY tenant_configs_tenant ON tenant_saas.tenant_configs
    FOR ALL USING (tenant_id = current_setting('app.tenant_id', true));

DROP POLICY IF EXISTS ai_custom_skills_tenant ON tenant_saas.ai_custom_skills;
CREATE POLICY ai_custom_skills_tenant ON tenant_saas.ai_custom_skills
    FOR ALL USING (tenant_id = current_setting('app.tenant_id', true));

DROP POLICY IF EXISTS merchant_onboarding_tenant ON public.merchant_onboarding;
CREATE POLICY merchant_onboarding_tenant ON public.merchant_onboarding
    FOR ALL USING (tenant_id = current_setting('app.tenant_id', true));

COMMIT;
