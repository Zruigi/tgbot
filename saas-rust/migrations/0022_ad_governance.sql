BEGIN;

CREATE TABLE IF NOT EXISTS groups.ad_group_policies (
    tenant_id text NOT NULL DEFAULT 'default',
    group_id bigint NOT NULL,
    is_enabled boolean NOT NULL DEFAULT false,
    warning_similarity double precision NOT NULL DEFAULT 0.50,
    warning_count integer NOT NULL DEFAULT 3,
    delete_similarity double precision NOT NULL DEFAULT 0.80,
    delete_count integer NOT NULL DEFAULT 5,
    exact_delete_count integer NOT NULL DEFAULT 6,
    mute_min_senders integer NOT NULL DEFAULT 3,
    mute_min_messages integer NOT NULL DEFAULT 6,
    mute_seconds integer NOT NULL DEFAULT 2592000,
    activated_by text,
    activated_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, group_id)
);

CREATE TABLE IF NOT EXISTS groups.ad_scan_jobs (
    job_id text PRIMARY KEY,
    tenant_id text NOT NULL DEFAULT 'default',
    group_id bigint NOT NULL,
    group_title text,
    requested_by text,
    status text NOT NULL DEFAULT 'prepared',
    progress integer NOT NULL DEFAULT 0,
    dry_run boolean NOT NULL DEFAULT true,
    activate_policy boolean NOT NULL DEFAULT false,
    source text NOT NULL DEFAULT 'agent',
    total_messages integer NOT NULL DEFAULT 0,
    candidate_clusters integer NOT NULL DEFAULT 0,
    confirmed_clusters integer NOT NULL DEFAULT 0,
    fingerprint_only_count integer NOT NULL DEFAULT 0,
    planned_delete_count integer NOT NULL DEFAULT 0,
    deleted_count integer NOT NULL DEFAULT 0,
    warning_sender_count integer NOT NULL DEFAULT 0,
    muted_sender_count integer NOT NULL DEFAULT 0,
    failure_count integer NOT NULL DEFAULT 0,
    summary_json text,
    error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    started_at timestamptz,
    finished_at timestamptz
);

CREATE INDEX IF NOT EXISTS idx_ad_scan_jobs_scope
    ON groups.ad_scan_jobs (tenant_id, group_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_ad_scan_jobs_status
    ON groups.ad_scan_jobs (status, created_at);

CREATE TABLE IF NOT EXISTS groups.ad_governance_clusters (
    cluster_id text PRIMARY KEY,
    job_id text NOT NULL,
    tenant_id text NOT NULL DEFAULT 'default',
    group_id bigint NOT NULL,
    representative_text text,
    exact_hash text,
    template_hash text,
    similarity double precision NOT NULL DEFAULT 1.0,
    occurrence_count integer NOT NULL DEFAULT 0,
    recent_count integer NOT NULL DEFAULT 0,
    sender_count integer NOT NULL DEFAULT 0,
    classification text NOT NULL DEFAULT 'pending',
    classification_source text,
    confidence double precision NOT NULL DEFAULT 0,
    reason text,
    action_tier text NOT NULL DEFAULT 'none',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ad_gov_clusters_job
    ON groups.ad_governance_clusters (job_id, classification, action_tier);

CREATE INDEX IF NOT EXISTS idx_ad_gov_clusters_tenant_group
    ON groups.ad_governance_clusters (tenant_id, group_id, created_at DESC);

CREATE TABLE IF NOT EXISTS groups.ad_governance_cluster_messages (
    cluster_id text NOT NULL,
    msg_id bigint NOT NULL,
    tenant_id text NOT NULL DEFAULT 'default',
    group_id bigint NOT NULL,
    tg_msg_id bigint,
    sender_id bigint,
    message_ts integer,
    exact_hash text,
    similarity double precision NOT NULL DEFAULT 1.0,
    is_actionable boolean NOT NULL DEFAULT false,
    PRIMARY KEY (cluster_id, msg_id)
);

CREATE INDEX IF NOT EXISTS idx_ad_gov_cluster_messages_msg
    ON groups.ad_governance_cluster_messages (group_id, tg_msg_id);

CREATE INDEX IF NOT EXISTS idx_ad_gov_cluster_messages_tenant
    ON groups.ad_governance_cluster_messages (tenant_id, group_id);

CREATE TABLE IF NOT EXISTS groups.ad_governance_actions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_key text NOT NULL UNIQUE,
    job_id text,
    tenant_id text NOT NULL DEFAULT 'default',
    group_id bigint NOT NULL,
    cluster_id text,
    action_type text NOT NULL,
    target_id text,
    status text NOT NULL DEFAULT 'planned',
    dry_run boolean NOT NULL DEFAULT true,
    payload_json text,
    error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    executed_at timestamptz
);

CREATE INDEX IF NOT EXISTS idx_ad_gov_actions_job
    ON groups.ad_governance_actions (job_id, action_type, status);

CREATE INDEX IF NOT EXISTS idx_ad_gov_actions_tenant_group
    ON groups.ad_governance_actions (tenant_id, group_id, created_at DESC);

CREATE TABLE IF NOT EXISTS groups.ad_warning_dedup (
    tenant_id text NOT NULL DEFAULT 'default',
    group_id bigint NOT NULL,
    family_hash text NOT NULL,
    sender_id bigint NOT NULL,
    window_key text NOT NULL,
    warned_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, group_id, family_hash, sender_id, window_key)
);

ALTER TABLE chat.messages
    ADD COLUMN IF NOT EXISTS agent_ui_json text;

COMMIT;
